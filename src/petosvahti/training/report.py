"""Render a training run as a model evaluation report (docs/templates format)."""

from typing import Any

from petosvahti.scoring.policy import APPROVE_BELOW, BLOCK_ABOVE
from petosvahti.training.train import TrainingResult

PATTERN_LABELS = {
    "app_scam": "APP scam (victim pays a mule)",
    "account_takeover": "Account takeover",
    "card_testing": "Card testing",
}


def _pct(x: float) -> str:
    return f"{100 * x:.1f} %"


def _eur(x: float) -> str:
    return f"€{x:,.0f}".replace(",", " ")


def _curve(rows: list[dict[str, Any]]) -> str:
    lines = ["| Risk ≥ | Precision | Recall | Flagged per 1 000 tx |", "|---|---|---|---|"]
    for r in rows:
        lines.append(
            f"| {r['threshold']} | {_pct(r['precision'])} | {_pct(r['recall'])} "
            f"| {r['alerts_per_1000']:.2f} |"
        )
    return "\n".join(lines)


def render(result: TrainingResult, artifact: str, sha: str) -> str:
    e = result.evaluation
    cfg = result.config
    h, d, b, lat, err = e["headline"], e["dataset"], e["baselines"], e["latency_ms"], e["errors"]
    model = result.model

    patterns = "\n".join(
        f"| {PATTERN_LABELS.get(k, k)} | {v['transactions']} | {_pct(v['recall_flagged'])} "
        f"| {_pct(v['blocked_share'])} | {v['median_risk']:.1f} |"
        for k, v in e["patterns"].items()
    )
    fn_reasons = "\n".join(f"- `{combo}` — {n}" for combo, n in err["false_negative_reasons"])
    fp_reasons = "\n".join(f"- `{combo}` — {n}" for combo, n in err["false_positive_reasons"])
    fn_patterns = ", ".join(
        f"{PATTERN_LABELS.get(p, p)}: {n}" for p, n in err["false_negative_patterns"]
    )
    fp_channels = ", ".join(f"{c}: {n}" for c, n in err["false_positive_channels"]) or "none"
    review_band = max(h["alerts_per_1000"], 0.0)

    return f"""# Model Evaluation Report — Isolation Forest baseline `{model.version}`

**Date:** {model.trained_at[:10]} · **Dataset:** Petosvahti synthetic Finnish stream — {cfg.n_customers:,} customers, \
seed {cfg.seed}, time-ordered splits {cfg.warmup_days} d warm-up / {cfg.train_days} d train / {cfg.calib_days} d \
calibration / {cfg.test_days} d test; test = {d["test_transactions"]:,} tx, {d["test_fraud"]} fraud \
({_pct(d["test_fraud_rate"])}) · **Seed:** {cfg.seed} · **Artifact:** `{artifact}` (sha256 `{sha}`)

*Generated by `petosvahti train --report`; every number below is reproducible from the seed. \
Model: `IsolationForest(n_estimators={cfg.n_estimators}, max_samples={cfg.max_samples})` [R18][R19] on \
{len(model.feature_names)} per-customer features, isotonic calibration to P(fraud), policy approve < {APPROVE_BELOW:g} ≤ \
review ≤ {BLOCK_ABOVE:g} < block.*

## Headline metrics

The test window is **replayed through the online `Scorer`** in time order — features, model, policy and the \
learning rule (blocked/reviewed payments never teach the profile) exactly as in production — so these are \
system metrics, not static-matrix metrics.

| Metric | Value | Target | Baseline comparison |
|---|---|---|---|
| PR-AUC | **{h["pr_auc"]:.3f}** | ≥ 0.70 (O1) | Supervised HistGradientBoosting (sees labels): {b["supervised_pr_auc"]:.3f} |
| ROC-AUC | {h["roc_auc"]:.4f} | — | — |
| Recall @ review threshold (flagged = review + block) | **{_pct(h["recall_flagged"])}** | | Static rules: {_pct(b["rules"]["recall"])} |
| Precision @ review threshold | {_pct(h["precision_flagged"])} | | Static rules: {_pct(b["rules"]["precision"])} |
| Recall @ block threshold | {_pct(h["recall_blocked"])} | | |
| Precision @ block threshold | {_pct(h["precision_blocked"])} | | |
| Legit payments blocked per 1 000 tx | {h["legit_blocked_per_1000"]:.3f} | | |
| Precision @ top-1 % | {_pct(h["precision_top1pct"])} | | ceiling = fraud rate / 1 % = {_pct(min(d["test_fraud_rate"] / 0.01, 1.0))} |
| Scoring latency p50 / p95 / p99 | {lat["p50"]:.2f} / {lat["p95"]:.2f} / {lat["p99"]:.2f} ms | p99 < 100 ms | scikit-learn `score_samples`: ~30 ms per row |

*Why PR-AUC and not accuracy [R20]: at {_pct(d["test_fraud_rate"])} fraud, predicting "all legit" scores \
{_pct(1 - d["test_fraud_rate"])} accuracy and catches nothing.*

**Static rules baseline** = flag if (≥ €1 000 to a new payee) or (≥ 5 attempts in an hour) or (new device \
from a new country) — the kind of rule set a bank starts with. It flags {b["rules"]["alerts_per_1000"]:.1f} \
per 1 000 tx.

**Business view:** of {_eur(h["fraud_value_eur"])} attempted fraud in the test window, \
{_eur(h["fraud_value_stopped_eur"])} was blocked outright and {_eur(h["fraud_value_held_eur"])} held for review.

## Threshold analysis

Cut-offs are chosen on the **calibration window** (first table) and only reported on test (second table), \
so the test set never tunes the policy.

**Calibration window**

{_curve(e["calibration_thresholds"])}

**Test window (replay)**

{_curve(e["thresholds"])}

**Chosen:** review at risk ≥ {APPROVE_BELOW:g}, block above {BLOCK_ABOVE:g}.

- *Review ≥ {APPROVE_BELOW:g}* — a human looks at anything with roughly a one-in-five or better chance of \
being fraud. Lowering the review cut-off to this level on the calibration curve buys several points of \
recall for a fraction of an extra case per 1 000 tx — a good trade when the alternative is an irrevocable \
instant loss. The review queue on test is {review_band:.2f} cases per 1 000 tx (≈ {review_band * 10:.0f} \
per 10 000), which a small fraud desk can clear. This is the GDPR Art. 22 human-in-the-loop band [R9].
- *Block > {BLOCK_ABOVE:g}* — automatic refusal only where precision is very high \
({_pct(h["precision_blocked"])} on test); on instant rails (≤ 10 s, irrevocable [R1]) a block is the only \
intervention that works, so it must rarely hit a genuine customer.
- The isotonic map is a step function, so neighbouring thresholds often give identical results \
(plateaus in the tables); moving a cut-off within a plateau changes nothing.

## Per-pattern detection (test)

| Pattern | Tx | Flagged (recall) | Blocked | Median risk |
|---|---|---|---|---|
{patterns}

## Error analysis

**False negatives: {err["false_negatives"]}** ({fn_patterns}); median amount {_eur(err["false_negative_median_eur"])}. \
Most common reason-code sets on missed fraud:

{fn_reasons}

- *Card testing*: the first one or two probes of a burst have no velocity yet and are €0.50–4 — on \
their own indistinguishable from buying a coffee. Detection kicks in once velocity builds up.
- *APP scam*: the victim uses their own phone, at home, so the only signals are amount + new payee + \
instant rail. Isolation Forest splits on one feature at a time and isolates *combinations* poorly. During \
development APP-scam recall was 18–37 % until three changes: isotonic instead of Platt calibration, the \
`instant_new_payee_log_amount` interaction feature, and a 24 h beneficiary cooling-off (an approved first \
transfer must not whitelist the mule for the second).

**False positives: {err["false_positives"]}** (channels: {fp_channels}). Reason-code sets:

{fp_reasons}

These are genuine customer behaviour that looks like fraud — a burst of new second-hand purchases, a \
large payment to a brand-new payee at night. {err["false_positives_blocked"]} of them were blocked; the \
rest were held for review, where an analyst (or a step-up confirmation in the app) can release them.

## Limitations & honesty section

- **Synthetic data, same author as the model.** The generator encodes my beliefs about Finnish fraud; \
the model is evaluated against those same beliefs. That is circular. These numbers show the pipeline \
works and the features carry signal; they do **not** predict performance on real bank traffic, where \
fraud adapts and labels are late, noisy and incomplete.
- **Kaggle benchmark not in this report.** The Kaggle credit-card set [R17] is PCA-anonymised card data with \
no customer, payee, device or rail — none of these features can be computed on it. \
`scripts/benchmark_kaggle.py` runs the same algorithm on it as a sanity check, separately.
- **Labels used twice:** for isotonic calibration and threshold choice, both on the calibration window, \
never on test. The forest itself is unsupervised.
- **Supervised reference is not tuned** and is trained on offline (learn-everything) features while being \
tested on online (approved-only) features; treat it as a rough upper bound, not a competitor.
- **Latency** is in-process, single-threaded, excluding HTTP and network, on a developer laptop. \
{lat["calls_over_10ms"]} of {d["test_transactions"]:,} calls took over 10 ms (worst {lat["max"]:.0f} ms); \
that looks like interpreter/OS pauses rather than model compute, but was not investigated. The API's \
`/metrics` exposes the same in-process measure for live traffic.
- **Concept drift is not modelled:** one stationary month of behaviour.

## Decision

Ship as the **baseline** for the scoring service and live demo. Next iteration: an autoencoder or a \
supervised challenger trained on analyst-confirmed `review` outcomes, compared on this same replay harness.
"""
